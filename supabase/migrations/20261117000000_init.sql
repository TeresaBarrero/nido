-- Perfiles: públicos para leer (nombre, barrio, valoración); cada cual edita el suyo.
create policy "profiles readable" on public.profiles for select using (true);
create policy "profiles own update" on public.profiles for update
  using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

-- Bebés: privados.
create policy "babies own" on public.babies for all
  using ((select auth.uid()) = profile_id) with check ((select auth.uid()) = profile_id);

-- Anuncios: los activos, reservados y vendidos son públicos; quien vende ve y gestiona los suyos.
create policy "listings public" on public.listings for select
  using (status in ('live','reserved','sold') or (select auth.uid()) = seller_id);
create policy "listings own insert" on public.listings for insert
  with check ((select auth.uid()) = seller_id);
create policy "listings own update" on public.listings for update
  using ((select auth.uid()) = seller_id) with check ((select auth.uid()) = seller_id);
create policy "listings own delete" on public.listings for delete
  using ((select auth.uid()) = seller_id);

-- Fotos: visibles si el anuncio lo es; solo quien vende añade o quita.
create policy "photos readable" on public.listing_photos for select
  using (exists (select 1 from public.listings l where l.id = listing_id));
create policy "photos own write" on public.listing_photos for all
  using (exists (select 1 from public.listings l where l.id = listing_id and l.seller_id = (select auth.uid())))
  with check (exists (select 1 from public.listings l where l.id = listing_id and l.seller_id = (select auth.uid())));

-- Favoritos y alertas: privados.
create policy "favorites own" on public.favorites for all
  using ((select auth.uid()) = profile_id) with check ((select auth.uid()) = profile_id);
create policy "alerts own" on public.alerts for all
  using ((select auth.uid()) = profile_id) with check ((select auth.uid()) = profile_id);

-- Conversaciones: solo sus dos participantes. La empieza quien compra.
create policy "conversations participants" on public.conversations for select
  using ((select auth.uid()) in (buyer_id, seller_id));
create policy "conversations buyer starts" on public.conversations for insert
  with check (
    (select auth.uid()) = buyer_id
    and exists (select 1 from public.listings l where l.id = listing_id and l.seller_id = conversations.seller_id)
  );

-- Mensajes: solo dentro de conversaciones propias y en nombre propio.
create policy "messages participants read" on public.messages for select
  using (exists (select 1 from public.conversations c
    where c.id = conversation_id and (select auth.uid()) in (c.buyer_id, c.seller_id)));
create policy "messages participants send" on public.messages for insert
  with check (
    (select auth.uid()) = sender_id
    and exists (select 1 from public.conversations c
      where c.id = conversation_id and (select auth.uid()) in (c.buyer_id, c.seller_id))
  );

-- Reservas: las ven quien compra y quien vende; la crea quien compra.
create policy "reservations parties read" on public.reservations for select
  using ((select auth.uid()) = buyer_id
    or exists (select 1 from public.listings l where l.id = listing_id and l.seller_id = (select auth.uid())));
create policy "reservations buyer creates" on public.reservations for insert
  with check ((select auth.uid()) = buyer_id);
create policy "reservations parties update" on public.reservations for update
  using ((select auth.uid()) = buyer_id
    or exists (select 1 from public.listings l where l.id = listing_id and l.seller_id = (select auth.uid())));

-- Valoraciones: públicas; se escriben en nombre propio.
create policy "reviews readable" on public.reviews for select using (true);
create policy "reviews own insert" on public.reviews for insert
  with check ((select auth.uid()) = author_id);

-- Notificaciones: privadas.
create policy "notifications own read" on public.notifications for select
  using ((select auth.uid()) = profile_id);
create policy "notifications own update" on public.notifications for update
  using ((select auth.uid()) = profile_id) with check ((select auth.uid()) = profile_id);


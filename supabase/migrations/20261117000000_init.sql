create table public.alerts (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(id) on delete cascade,
  filters jsonb not null,
  created_at timestamptz not null default now()
);

-- ============================================================
-- Chat
-- ============================================================
create table public.conversations (
  id uuid primary key default gen_random_uuid(),
  listing_id bigint not null references public.listings(id) on delete cascade,
  buyer_id uuid not null references public.profiles(id) on delete cascade,
  seller_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (listing_id, buyer_id),
  check (buyer_id <> seller_id)
);

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null default '' check (char_length(body) <= 2000),
  kind text not null default 'text' check (kind in ('text','meeting_proposal')),
  payload jsonb,
  created_at timestamptz not null default now()
);
create index on public.messages(conversation_id, created_at);

-- ============================================================
-- Reservas y valoraciones
-- ============================================================
create table public.reservations (
  id uuid primary key default gen_random_uuid(),
  listing_id bigint not null references public.listings(id) on delete cascade,
  buyer_id uuid not null references public.profiles(id) on delete cascade,
  meeting_place text not null,
  meeting_at timestamptz not null,
  amount numeric(8,2) not null check (amount > 0),
  -- Protección Nido: 5 % del precio, mínimo 0,50 €.
  fee numeric(8,2) not null check (fee = greatest(0.50, round(amount * 0.05, 2))),
  status text not null default 'paid' check (status in ('paid','delivered','cancelled')),
  delivery_code char(4) not null default lpad((floor(random() * 10000))::int::text, 4, '0'),
  created_at timestamptz not null default now()
);

create table public.reviews (
  id uuid primary key default gen_random_uuid(),
  reservation_id uuid references public.reservations(id) on delete cascade,
  author_id uuid not null references public.profiles(id) on delete cascade,
  target_id uuid not null references public.profiles(id) on delete cascade,
  stars smallint not null check (stars between 1 and 5),
  text text check (text is null or char_length(text) <= 500),
  created_at timestamptz not null default now(),
  unique (reservation_id, author_id),
  check (author_id <> target_id)
);

-- La media de valoraciones del perfil se actualiza sola.
create function public.refresh_rating() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.profiles p set
    rating_avg = coalesce((select round(avg(stars)::numeric, 1) from public.reviews where target_id = new.target_id), 0),
    rating_count = (select count(*) from public.reviews where target_id = new.target_id)
  where p.id = new.target_id;
  return new;
end $$;

create trigger reviews_refresh_rating
  after insert on public.reviews
  for each row execute function public.refresh_rating();

create table public.notifications (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null,
  title text not null,
  body text,
  link text,
  read boolean not null default false,
  created_at timestamptz not null default now()
);
create index on public.notifications(profile_id, created_at desc);

-- ============================================================
-- Perfil automático al registrarse
-- ============================================================
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, name)
  values (new.id, coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(new.email, '@', 1)));
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


-- ============================================================
-- Perfiles
-- ============================================================
-- Un perfil por persona. Los de quien inicia sesión se crean solos (trigger más abajo)
-- con el mismo id que su usuario; los de ejemplo (seed) no tienen usuario.
create table public.profiles (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 60),
  neighborhood text,
  lat double precision,
  lng double precision,
  verified boolean not null default false,
  rating_avg numeric(2,1) not null default 0,
  rating_count integer not null default 0,
  tone text not null default 'sky' check (tone in ('sky','mint','peach','butter','lavender','pink')),
  created_at timestamptz not null default now()
);

-- El bebé: solo nombre opcional y fecha de nacimiento. Nunca fotos.
create table public.babies (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(id) on delete cascade,
  name text check (name is null or char_length(name) <= 40),
  birth_date date not null
);
create index on public.babies(profile_id);

-- ============================================================
-- Anuncios
-- ============================================================
create table public.listings (
  id bigint generated by default as identity primary key,
  seller_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (char_length(title) between 3 and 80),
  description text not null default '',
  section text not null check (section in (
    'Ropa y calzado','Paseo y viaje','Dormir','Habitación','Baño y cambio','Comida','Juego','Seguridad en casa')),
  subcategory text not null,
  stages text[] not null default '{}' check (stages <@ array['0-3','3-6','6-12','12-24','24-48']),
  condition text not null check (condition in (
    'Nuevo precintado','Nuevo sin etiqueta','Como nuevo','Buen estado','Con señales de uso')),
  usage text,
  includes text,
  is_complete boolean not null default true,
  hygiene text[] not null default '{}',
  price numeric(8,2) not null check (price > 0),
  new_price numeric(8,2) check (new_price is null or new_price > 0),
  delivery text not null default 'hand' check (delivery in ('hand','hand_ship')),
  lot_count integer check (lot_count is null or lot_count > 1),
  spec_value text,
  meeting_point text,
  -- 'review': pendiente de revisión (sillas de coche nuevas).
  status text not null default 'live' check (status in ('review','live','paused','reserved','sold')),
  lat double precision,
  lng double precision,
  created_at timestamptz not null default now(),

  -- Regla 1 y 2: sillas de coche e higiene, solo nuevas y precintadas.
  constraint car_seats_and_hygiene_only_sealed check (
    subcategory not in ('Sillas de coche (solo nuevas)','Higiene nueva') or condition = 'Nuevo precintado'
  )
);
create index on public.listings(status);
create index on public.listings(seller_id);
create index on public.listings(section);

-- Las sillas de coche entran siempre en revisión y quien vende no puede publicarlas por su cuenta.
create function public.enforce_car_seat_review() returns trigger
language plpgsql as $$
declare
  car_seat constant text := 'Sillas de coche (solo nuevas)';
begin
  -- Solo afecta a usuarios de la app; el equipo de Nido revisa desde el panel de Supabase.
  if coalesce(auth.jwt() ->> 'role', '') <> 'authenticated' then
    return new;
  end if;
  if tg_op = 'INSERT' then
    if new.subcategory = car_seat then new.status := 'review'; end if;
  else
    -- Pasar un anuncio a silla de coche lo devuelve a revisión.
    if new.subcategory = car_seat and old.subcategory <> car_seat then
      new.status := 'review';
    -- Un anuncio en revisión no sale de ella, ni cambiándole la categoría.
    elsif old.status = 'review' and new.status <> 'review' then
      raise exception 'Las sillas de coche se publican tras la revisión de Nido';
    end if;
  end if;
  return new;
end $$;

create trigger listings_car_seat_review
  before insert or update on public.listings
  for each row execute function public.enforce_car_seat_review();

create table public.listing_photos (
